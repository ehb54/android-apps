/**
 * Compose for Desktop (JetBrains' Compose Multiplatform on the JVM), with the
 * same Material 3 the Android apps use, plus `androidx.annotation` so
 * `@StringRes` code copied from an Android app compiles.
 */
internal fun Project.configureComposeDesktop() {
    configureKotlinJvm()
    pluginManager.apply("org.jetbrains.compose")
    pluginManager.apply("org.jetbrains.kotlin.plugin.compose")
    val compose = libs.findVersion("composeMultiplatform").get().requiredVersion
    dependencies {
        add("implementation", "org.jetbrains.compose.desktop:desktop-jvm-${desktopPlatform()}:$compose")
        add("implementation", libs.library("jetbrains-compose-material3"))
        add("implementation", libs.library("kotlinx-coroutines-swing"))
        add("implementation", libs.library("androidx-annotation"))
        add("testImplementation", libs.library("jetbrains-compose-ui-test-junit4"))
    }
}

/**
 * This computer's desktop platform as Compose names its artifacts, e.g.
 * "macos-x64": installers are built for the OS and processor they are built on.
 */
private fun desktopPlatform(): String {
    val os = System.getProperty("os.name").lowercase()
    val name = when {
        os.startsWith("mac") -> "macos"
        os.startsWith("windows") -> "windows"
        else -> "linux"
    }
    val arch = if (System.getProperty("os.arch") in setOf("aarch64", "arm64")) "arm64" else "x64"
    return "$name-$arch"
}

/** Which Android resources a desktop module reads (see [GenerateAndroidResources]). */
abstract class AndroidResourcesExtension {
    /** Android res folders, in order; later ones override earlier ones' entries. */
    abstract val resDirs: ConfigurableFileCollection

    /** Package of the generated `R`. */
    abstract val packageName: Property<String>

    /** Android assets folders, read through the Context stand-in's `assets`. */
    abstract val assetDirs: ConfigurableFileCollection
}

/** Registers the `androidResources` extension and the task that turns it into `R` and classpath files. */
internal fun Project.registerAndroidResources(packageId: Int): AndroidResourcesExtension {
    val settings = extensions.create<AndroidResourcesExtension>("androidResources")
    val generate = tasks.register<GenerateAndroidResources>("generateAndroidResources") {
        resDirs.from(settings.resDirs)
        assetDirs.from(settings.assetDirs)
        packageName.set(settings.packageName)
        this.packageId.set(packageId)
        kotlinDir.set(layout.buildDirectory.dir("generated/androidResources/kotlin"))
        resourcesDir.set(layout.buildDirectory.dir("generated/androidResources/resources"))
    }
    extensions.getByType<KotlinJvmProjectExtension>().sourceSets.named("main") {
        kotlin.srcDir(generate.flatMap { it.kotlinDir })
        resources.srcDir(generate.flatMap { it.resourcesDir })
    }
    return settings
}

/**
 * `BuildConfig` for a desktop app, shaped like Android's (VERSION_NAME,
 * VERSION_CODE, BUILD_TIME, DEBUG), so shared-looking code reads the same.
 */
@CacheableTask
abstract class GenerateBuildConfig : DefaultTask() {
    @get:Input
    abstract val packageName: Property<String>

    @get:Input
    abstract val versionName: Property<String>

    @get:Input
    abstract val versionCode: Property<Int>

    @get:Input
    abstract val buildTime: Property<String>

    @get:Input
    abstract val debug: Property<Boolean>

    @get:OutputDirectory
    abstract val outputDir: DirectoryProperty

    @TaskAction
    fun generate() {
        val pkg = packageName.get()
        val out = outputDir.get().asFile.apply { deleteRecursively() }
        fun quoted(value: String) = "\"" + value.replace("\\", "\\\\").replace("\"", "\\\"").replace("$", "\\$") + "\""
        java.io.File(out, pkg.replace('.', '/')).apply { mkdirs() }.resolve("BuildConfig.kt").writeText(
            """
            |// Generated by build-logic's GenerateBuildConfig. Do not edit.
            |package $pkg
            |
            |object BuildConfig {
            |    const val VERSION_NAME: String = ${quoted(versionName.get())}
            |    const val VERSION_CODE: Int = ${versionCode.get()}
            |    const val BUILD_TIME: String = ${quoted(buildTime.get())}
            |    const val DEBUG: Boolean = ${debug.get()}
            |}
            |
            """.trimMargin(),
        )
    }
}

/** Version numbers as for Android apps (tools/version-env.sh sets them), compiled into `BuildConfig`. */
internal fun Project.registerBuildConfig(packageName: String) {
    val generate = tasks.register<GenerateBuildConfig>("generateBuildConfig") {
        this.packageName.set(packageName)
        versionName.set(stringProperty("appVersionName", "0.0.0-dev"))
        versionCode.set(stringProperty("appVersionCode", "1").toInt())
        buildTime.set(stringProperty("appBuildTime", "dev build"))
        // Every build here is a test build, like the debug APKs; -PappDebug=false for a real release.
        debug.set(stringProperty("appDebug", "true").toBoolean())
        outputDir.set(layout.buildDirectory.dir("generated/buildConfig"))
    }
    extensions.getByType<KotlinJvmProjectExtension>().sourceSets.named("main") {
        kotlin.srcDir(generate.flatMap { it.outputDir })
    }
}
